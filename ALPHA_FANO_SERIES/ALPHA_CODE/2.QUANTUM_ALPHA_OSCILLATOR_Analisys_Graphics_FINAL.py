print("  [4] Dimensionless structure operator (not a physical Hamiltonian)")
print("  [5] Subtractive chirality: K = 10 - F (stability anchoring)")
print("=" * 80)
print()

# =================================================================================
# RUN SIMULATION
# =================================================================================
start_time = time.time()

S_values = []
all_sequences = []  # Store for graphics
sequence = np.zeros(depth, dtype=np.int64)

for i in range(n_iterations):
    # Generate independent draws for each depth (Seal 1)
    for j in range(depth):
        sequence[j] = np.random.choice(q_space, p=probabilities)

    S = compute_structure_value(sequence)
    S_values.append(S)
    all_sequences.append(sequence.copy())

    if (i + 1) % 100_000 == 0:
        elapsed = time.time() - start_time
        print(f"  Progress: {i+1:,}/{n_iterations:,} | Time: {elapsed:.1f}s")

elapsed_total = time.time() - start_time

# =================================================================================
# RESULTS
# =================================================================================
S_array = np.array(S_values)
mean_S = np.mean(S_array)
std_S = np.std(S_array)
min_S = np.min(S_array)
max_S = np.max(S_array)

print()
print("=" * 80)
print("RESULTS")
print("=" * 80)
print(f"Total time: {elapsed_total:.2f} seconds")
print(f"Mean ⟨S⟩ (predicted α⁻¹): {mean_S:.12f}")
