# ============================================================================
# GENERATOR MATRIX G(theta) = L_geo * I + epsilon * K
# ============================================================================

def create_generator_matrix(theta, R=R, D=D, epsilon=0.0):
    """
    Continuous generator G(θ) = L_geo * I + ε * K
    No fitting. Pure geometry + quantum coupling.
    """
    # 1. Geometric Lagrangian (Background)
    d_val = R * np.sin(theta)
    v_val = R * np.cos(theta)
    chord = 2 * np.sqrt(max(R**2 - d_val**2, 0))

    # Using 1/8 for the surface term (as in the original paper 2)
    L_geo = 4 * v_val**2 + (1/R) * d_val**2 + (1/8) * chord

    # 2. Vacuum structure (Identity) - L_geo acts equally on all virtual microstates
    G_geo = L_geo * np.eye(D)

    # 3. Quantum Operator K (Continued fractions)
    # Simple shift matrix as placeholder (replace with exact K from Paper 2)
    K_matrix = np.zeros((D, D))
    for i in range(D - 1):
        K_matrix[i, i+1] = 1.0
        K_matrix[i+1, i] = 1.0
    K_matrix[0, D-1] = 1.0  # periodicity
    K_matrix[D-1, 0] = 1.0

    # Normalize K matrix
    if np.max(np.abs(K_matrix)) > 0:
        K_matrix = K_matrix / np.max(np.abs(K_matrix))

    # 4. Total Generator
    G_total = G_geo + epsilon * K_matrix

    return G_total

# ============================================================================
# EXACT CIRCULAR MPS SIMULATION (UNIFORM STEPS)
# ============================================================================

def simulate_circular_mps_exact(N_steps=2000, epsilon=0.0, verbose=True, use_progress=False):
    """
    Contract the product of exact matrix exponentials along the circle.
    Partition function Z = Tr(∏ T_i) with T = exp(G * dθ)
    Action S = ln(λ_max) where λ_max is the dominant eigenvalue.
    """
    theta_vals = np.linspace(0, 2*np.pi, N_steps, endpoint=False)
    d_theta = theta_vals[1] - theta_vals[0]

    # Initialize transfer matrix (identity)
    M = np.eye(D)

    # Storage for analysis (downsampled for memory)
    L_vals = []
    step_sampling = max(1, N_steps // 1000)  # store only 1000 points

    # Progress bar
    iterator = tqdm(theta_vals, desc="Contracting MPS") if use_progress else theta_vals

    # Contraction along the circle using exact matrix exponential
    for i, theta in enumerate(iterator):
        G = create_generator_matrix(theta, R, D, epsilon)

        # EXACT TRANSFORMATION: matrix exponential exp(G * dθ)
        T_theta = expm(G * d_theta)

        # Contract
        M = T_theta @ M

        # Store Lagrangian density (downsampled)
        if i % step_sampling == 0:
            d_val = R * np.sin(theta)
            v_val = R * np.cos(theta)
            chord = 2 * np.sqrt(max(R**2 - d_val**2, 0))
            L_vals.append(4 * v_val**2 + (1/R) * d_val**2 + (1/8) * chord)

    # Extract dominant eigenvalue (Perron-Frobenius)
    eigenvalues = eig(M, left=False, right=False)
    lambda_max = np.max(np.real(eigenvalues))

    # Action: S = ln(Z) where Z = λ_max
    S_eff = np.log(lambda_max)

    # Reconstruct full theta range for stored L_vals
    theta_stored = np.linspace(0, 2*np.pi, len(L_vals))

    if verbose:
        target = 4*R**3 + R**2 + R
        print(f"\nResults (N_steps = {N_steps:,}):")
        print(f"  Dominant eigenvalue λ_max = {lambda_max:.10e}")
        print(f"  Geometric action S_geo = ln(λ_max) = {S_eff:.12f}")
        print(f"  Target (4π³+π²+π) = {target:.12f}")
        print(f"  Error = {abs(S_eff - target):.2e}")

    return S_eff, L_vals, theta_stored

