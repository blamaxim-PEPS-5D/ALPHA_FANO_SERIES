def compute_S_alpha(N_steps):
    """Compute S_alpha = ln(λ_max) - π"""
    theta_vals = np.linspace(0, 2*np.pi, N_steps, endpoint=False)
    d_theta = theta_vals[1] - theta_vals[0]
