"""
Extended Sensitivity & Asymptotic Invariance Test for tau (E_int parameter)
Tests wide logarithmic range tau in [0.1, 100.0] and uniform asymptotic limit (tau -> infinity).
"""

import numpy as np
from mpmath import mp
import time

# High precision setup
mp.dps = 200
pi_mp = mp.pi

def A(x):
    return 4*x**3 + x**2 + x

A_pi = A(pi_mp)
A_third_derivative = mp.mpf(24)
zero_order_term = A_pi
curvature_correction = 1 / (A_third_derivative * A_pi)
const_factor = 1 / (A_pi**2 * pi_mp**2)

codata_2022 = mp.mpf("137.035999177")

# Test settings
depth = 20
max_q = 45
n_iterations = 50_000  # Veloce ed efficace per ampio scan
q_space = np.arange(1, max_q + 1)

def compute_structure_value(sequence):
    f = mp.mpf(str(sequence[-1]))
    for q in reversed(sequence[:-1]):
        f = mp.mpf(str(q)) + 1 / f
    f = 1 / f
    K = mp.mpf(10) - f
    quantum_term = const_factor / K
    S = zero_order_term - curvature_correction - quantum_term
    return float(S)

def run_simulation(probabilities, label):
    S_values = []
    sequence = np.zeros(depth, dtype=np.int64)
    start_time = time.time()

    for _ in range(n_iterations):
        sequence[:] = np.random.choice(q_space, size=depth, p=probabilities)
        S_values.append(compute_structure_value(sequence))

    elapsed = time.time() - start_time
    mean_S = np.mean(S_values)
    std_S = np.std(S_values)
    diff = mean_S - float(codata_2022)
    return mean_S, std_S, diff, elapsed

print("=" * 85)
print("TEST 1: LOGARITHMIC SENSITIVITY SCAN FOR tau (0.1 to 100.0)")
print("=" * 85)
print(f"{'tau':<10} {'Mean <S>':<20} {'Diff from CODATA':<25} {'Std Dev':<12} {'Time (s)':<8}")
print("-" * 85)

tau_log_values = [0.1, 0.5, 1.0, 3.0, 5.0, 10.0, 50.0, 100.0]
log_results = {}

for tau in tau_log_values:
    E_int = mp.mpf(tau)
    weights = [mp.exp(-q / (2 * E_int)) for q in range(1, max_q + 1)]
    total_weight = sum(weights)
    probs = [float(w / total_weight) for w in weights]

    mean_S, std_S, diff, elapsed = run_simulation(probs, f"tau={tau}")
    log_results[tau] = mean_S
    print(f"{tau:<10.1f} {mean_S:<20.12f} {diff:<+25.2e} {std_S:<12.2e} {elapsed:<8.2f}")

# Check delta nel range fisico centrale [1.0, 10.0] e range esteso
means_central = [log_results[t] for t in [1.0, 3.0, 5.0, 10.0]]
delta_central = max(means_central) - min(means_central)

print("-" * 85)
print(f"Max variation in <S> within physical band tau in [1.0, 10.0]: {delta_central:.2e}")
if delta_central < 1e-8:
    print("✅ PHYSICAL BAND STABILITY CONFIRMED (< 1e-8)")

print("\n" + "=" * 85)
print("TEST 2: ASYMPTOTIC UNIFORM LIMIT (tau -> infinity, P(q) = 1/45)")
print("=" * 85)

uniform_probs = [1.0 / max_q] * max_q
mean_u, std_u, diff_u, elapsed_u = run_simulation(uniform_probs, "Uniform Limit")

print(f"{'Limit':<10} {'Mean <S>':<20} {'Diff from CODATA':<25} {'Std Dev':<12} {'Time (s)':<8}")
print("-" * 85)
print(f"{'tau -> inf':<10} {mean_u:<20.12f} {diff_u:<+25.2e} {std_u:<12.2e} {elapsed_u:<8.2f}")

print("\n" + "=" * 85)
print("EXTENDED ANALYSIS COMPLETE")
print("=" * 85)