import mpmath as mp
import numpy as np
import matplotlib.pyplot as plt

# Set precision to 50 decimal digits
mp.dps = 50

# ============================================================================
# 1. PURE STRUCTURAL PARAMETERS (GEOMETRIC INPUTS - NO FITTING)
# ============================================================================
D = 45                                # Bond dimension = dim(adj SO(10))
T = mp.mpf(8)                         # String tension (√T = 2√2)
PHASE = mp.pi / 6                     # Topological phase from hinge term
DIM_H_FANO = 105                      # dim(adj SO(15)) = 105
B_EM_SM = mp.mpf(4.1)                 # Standard Model beta coefficient at M_Z
M_Z = mp.mpf(91.1876)                 # Z boson mass (GeV)
M_PLANCK = mp.mpf(1.2209e19)          # Planck mass (GeV)

# ============================================================================
# 2. ALGEBRAIC DERIVATIONS (HIGH PRECISION)
# ============================================================================

def calculate_entanglement():
    """S = 2√(1 + sin²(2θ)) with θ = π/6 → √7"""
    sin_2theta = mp.sin(2 * PHASE)
    return 2 * mp.sqrt(1 + sin_2theta**2)

def calculate_deficit(s_realized):
    """ΔS = √8 - √7"""
    s_max = mp.sqrt(T)
    return s_max - s_realized

def calculate_alpha_gut_inv(s_realized):
    """α_GUT^{-1} = dim(H_Fano) / entanglement eigenvalue = 105/√7 = 15√7"""
    return DIM_H_FANO / s_realized

def calculate_m_gut(delta_s):
    """M_GUT = M_Pl · ΔS"""
    return M_PLANCK * delta_s

def calculate_threshold_correction(s_max, delta_s):
    """δ_th = (1/2π) ln(√8 / ΔS)"""
    return (1 / (2 * mp.pi)) * mp.log(s_max / delta_s)

def calculate_delta_b_geom():
    """Δb_geom = dim(SO(15)) / dim(SO(5)) = 105 / 10 = 10.5"""
    dim_SO5_adj = 10
    return mp.mpf(DIM_H_FANO) / dim_SO5_adj

def calculate_delta_b_bound(delta_s):
    """Δb_bound = ΔS / (2π)"""
    return delta_s / (2 * mp.pi)

def calculate_b_em_eff(b_sm, delta_b_geom, delta_b_bound):
    """b_EM^eff = b_EM^SM + Δb_geom + Δb_bound"""
    return b_sm + delta_b_geom + delta_b_bound

def calculate_alpha_em_inv(alpha_gut_inv, b_em_eff, log_ratio, delta_th):
    """Solve RGE for alpha_EM^{-1}(M_Z)"""
    return alpha_gut_inv + (b_em_eff / (2 * mp.pi)) * log_ratio + delta_th

