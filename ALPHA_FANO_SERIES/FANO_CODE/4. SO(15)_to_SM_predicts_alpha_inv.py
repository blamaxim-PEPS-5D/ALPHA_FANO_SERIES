def generate_sensitivity_plots(results):
    """Generate sensitivity plots for the prediction"""

    alpha_gut_inv = results['alpha_gut_inv']
    delta_th = results['delta_th']
    log_ratio = results['log_ratio']
    b_em_nominal = results['b_em_eff']
    alpha_exp = results['alpha_em_inv_exp']

    # Range for b_EM variation (±10%)
    b_range = np.linspace(b_em_nominal * 0.95, b_em_nominal * 1.05, 100)
    alpha_pred_range = [alpha_gut_inv + (b / (2 * np.pi)) * log_ratio + delta_th for b in b_range]

    # Range for log ratio variation (±5%)
    log_range = np.linspace(log_ratio * 0.95, log_ratio * 1.05, 100)
    alpha_pred_log = [alpha_gut_inv + (b_em_nominal / (2 * np.pi)) * log_r + delta_th for log_r in log_range]

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

    # Sensitivity to b_EM
    ax1.plot(b_range, alpha_pred_range, 'b-', linewidth=2)
    ax1.axhline(y=alpha_exp, color='r', linestyle='--', label=f'Experimental {alpha_exp:.3f}')
    ax1.axvline(x=b_em_nominal, color='gray', linestyle=':', alpha=0.5)
    ax1.set_xlabel(r'$b_{\mathrm{EM}}^{\mathrm{eff}}$')
    ax1.set_ylabel(r'Predicted $\alpha_{\mathrm{EM}}^{-1}(M_Z)$')
    ax1.set_title('Sensitivity: Prediction vs b_EM')
    ax1.legend()
    ax1.grid(True, alpha=0.3)

    # Sensitivity to ln(M_GUT/M_Z)
    ax2.plot(log_range, alpha_pred_log, 'g-', linewidth=2)
    ax2.axhline(y=alpha_exp, color='r', linestyle='--', label=f'Experimental {alpha_exp:.3f}')
    ax2.axvline(x=log_ratio, color='gray', linestyle=':', alpha=0.5)
    ax2.set_xlabel(r'$\ln(M_{\mathrm{GUT}}/M_Z)$')
    ax2.set_ylabel(r'Predicted $\alpha_{\mathrm{EM}}^{-1}(M_Z)$')
    ax2.set_title('Sensitivity: Prediction vs Log Ratio')
    ax2.legend()
    ax2.grid(True, alpha=0.3)

    plt.tight_layout()
    plt.savefig('fano2_22_sensitivity.png', dpi=150, bbox_inches='tight')
    plt.show()

    print("Figure 3: fano2_22_sensitivity.png")

